// THE CONSTANTS THE KERNELS SHARE WITH RUST: one source for both sides.
//
// Rust reads them where they always were (`step`, `op_abi`, `runtime` re-export them). Under the
// `nvcc` feature `build.rs` `include!`s this file and writes [`cuda_header`] into
// `$OUT_DIR/scratchy_consts.cuh`, which nvcc force-includes into every kernel (`-include`), so a
// kernel reads `scratchy::GEMV_CHUNK` instead of restating 256. Plain Rust with no dependency and
// no inner attribute, as `include!` needs.

/// Defines each constant and [`cuda_header`], which spells every one of them for the kernels.
macro_rules! kernel_consts {
    ($($(#[$m:meta])* $name:ident: $t:ty = $v:expr;)*) => {
        $($(#[$m])* pub const $name: $t = $v;)*

        /// `scratchy_consts.cuh`: every constant above under its own name in `namespace scratchy`,
        /// a scalar as a `uint32_t`, a slice or tuple as a `uint32_t` array in its order.
        pub fn cuda_header() -> String {
            let mut h = String::from(
                "// Generated by scratchy-target-cuda's build.rs from src/kernel_consts.rs.\n\
                 #pragma once\n#include <cstdint>\nnamespace scratchy {\n",
            );
            $(h.push_str(&CudaConst::spell(&$name, stringify!($name)));)*
            h.push_str("}  // namespace scratchy\n");
            h
        }
    };
}

/// A constant's C++ spelling in the header.
trait CudaConst {
    fn spell(&self, name: &str) -> String;
}

impl CudaConst for u32 {
    fn spell(&self, name: &str) -> String {
        format!("inline constexpr uint32_t {name} = {self}u;\n")
    }
}

/// `{a}u, {b}u, …` of `values`.
fn elements(values: &[u32]) -> String {
    let each: Vec<String> = values.iter().map(|v| format!("{v}u")).collect();
    each.join(", ")
}

impl CudaConst for &[u32] {
    fn spell(&self, name: &str) -> String {
        format!(
            "inline constexpr uint32_t {name}[] = {{{}}};\n",
            elements(self)
        )
    }
}

impl CudaConst for (u32, u32) {
    fn spell(&self, name: &str) -> String {
        [self.0, self.1].as_slice().spell(name)
    }
}

impl CudaConst for (u32, u32, u32) {
    fn spell(&self, name: &str) -> String {
        [self.0, self.1, self.2].as_slice().spell(name)
    }
}

